#!/usr/bin/env python3
"""STEP 3 of the CAD -> URDF pipeline: the SRDF (Semantic Robot Description).

The URDF says what the robot IS; the SRDF says how to USE it:
  * planning groups (which joints move together)
  * named states ("home", "ready")
  * end effector
  * passive joints (here: elbows + platform joint -> not actuated!)
  * which link pairs never need collision checking

The collision matrix is computed exactly like the MoveIt Setup Assistant
does it: sample many valid configurations, collision-check every link pair
with the collision meshes and disable pairs that are
  Adjacent (parent/child), Always in collision, or Never in collision.
Because a parallel robot only has valid configurations ON the loop, we
sample *platform poses* and use the inverse kinematics (sampling joints
independently, like the Setup Assistant does, would break the loops).

Usage:  python3 tools/cad_to_urdf/step3_generate_srdf.py [--samples 3000]
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from itertools import combinations
from pathlib import Path

import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "ros2_ws" / "src" / "pm3rrr_core"))
sys.path.insert(0, str(Path(__file__).parent))

from pm3rrr_core import Pm3rrrKinematics  # noqa: E402
from step4_validate_urdf import expand_xacro, resolve_package_uris  # noqa: E402

OUT = ROOT / "ros2_ws" / "src" / "pm3rrr_description" / "config" / "pm3rrr.srdf"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=3000)
    a = ap.parse_args()
    import yourdfpy

    with tempfile.NamedTemporaryFile("w", suffix=".urdf", delete=False) as f:
        f.write(resolve_package_uris(expand_xacro()))
    robot = yourdfpy.URDF.load(f.name, load_meshes=False)

    links = [l.name for l in robot.robot.links if l.collisions]
    meshes = {}
    for l in robot.robot.links:
        if l.collisions:
            c = l.collisions[0]
            m = trimesh.load(c.geometry.mesh.filename)
            if c.origin is not None:
                m.apply_transform(c.origin)
            meshes[l.name] = m
    adjacent = set()
    parents = {j.child: j.parent for j in robot.robot.joints}
    for child, parent in parents.items():
        # walk up through link-less frames (no collision geometry)
        while parent not in meshes and parent in parents:
            parent = parents[parent]
        if child in meshes and parent in meshes:
            adjacent.add(tuple(sorted((child, parent))))

    kin = Pm3rrrKinematics()
    rng = np.random.default_rng(0)
    pairs = list(combinations(sorted(links), 2))
    hits = {p: 0 for p in pairs}
    n = 0
    while n < a.samples:
        pose = (rng.uniform(-0.03, 0.03), rng.uniform(-0.03, 0.03), rng.uniform(-0.6, 0.6))
        ik = kin.ik(pose)
        if not ik.ok:
            continue
        n += 1
        robot.update_cfg(kin.joint_state(pose, ik))
        cm = trimesh.collision.CollisionManager()
        for name, m in meshes.items():
            cm.add_object(name, m, transform=robot.get_transform(name, "world"))
        _, names = cm.in_collision_internal(return_names=True)
        for p in names:
            hits[tuple(sorted(p))] += 1

    disabled = []
    for p in pairs:
        if p in adjacent:
            disabled.append((p, "Adjacent"))
        elif hits[p] == n:
            disabled.append((p, "Always"))
        elif hits[p] == 0:
            disabled.append((p, "Never"))
    enabled = [p for p in pairs if p not in {d[0] for d in disabled}]
    print(f"{n} valid configurations sampled, {len(pairs)} link pairs:")
    for reason in ("Adjacent", "Always", "Never"):
        print(f"  {reason:8s}: {sum(1 for d in disabled if d[1] == reason)} pairs disabled")
    print(f"  checked : {len(enabled)} pairs stay enabled (can really collide):")
    for p in enabled:
        print(f"      {p[0]} <-> {p[1]}  ({100*hits[p]/n:.1f} % of samples)")

    dc = "\n".join(f'  <disable_collisions link1="{p[0]}" link2="{p[1]}" reason="{r}"/>' for p, r in disabled)
    srdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!--
  SRDF of the planar 3-RRR parallel manipulator.
  GENERATED by tools/cad_to_urdf/step3_generate_srdf.py ({n} sampled poses).

  NOTE for MoveIt users: MoveIt plans for serial (tree) chains. For this
  closed-chain robot the "platform_motors" group is used for joint-space
  motions and named states, while Cartesian motions of the platform are
  generated by pm3rrr_core (analytic IK) - see docs/learning/12_ros2_architecture.md.
-->
<robot name="pm3rrr">

  <!-- the robot is bolted to the table -->
  <virtual_joint name="virtual_joint" type="fixed" parent_frame="world" child_link="base_link"/>

  <!-- ===== planning groups ===== -->
  <group name="platform_motors">
    <joint name="leg1_motor_joint"/>
    <joint name="leg2_motor_joint"/>
    <joint name="leg3_motor_joint"/>
  </group>
  <group name="leg1"><chain base_link="base_link" tip_link="leg1_distal_link"/></group>
  <group name="leg2"><chain base_link="base_link" tip_link="leg2_distal_link"/></group>
  <group name="leg3"><chain base_link="base_link" tip_link="leg3_distal_link"/></group>
  <group name="platform"><link name="platform_link"/><link name="platform_center"/><link name="tool0"/></group>

  <!-- ===== named states (motor joints; 0 = servo centre = home pose) ===== -->
  <group_state name="home" group="platform_motors">
    <joint name="leg1_motor_joint" value="0"/>
    <joint name="leg2_motor_joint" value="0"/>
    <joint name="leg3_motor_joint" value="0"/>
  </group_state>

  <end_effector name="platform_tool" parent_link="leg1_distal_link" group="platform" parent_group="leg1"/>

  <!-- ===== passive (non-actuated) joints of the closed chain ===== -->
  <passive_joint name="leg1_elbow_joint"/>
  <passive_joint name="leg2_elbow_joint"/>
  <passive_joint name="leg3_elbow_joint"/>
  <passive_joint name="leg1_platform_joint"/>

  <!-- ===== self-collision matrix ===== -->
{dc}
</robot>
"""
    OUT.write_text(srdf)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
